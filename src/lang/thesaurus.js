export function synonymsFor(word) {
  const w = word.toLowerCase();
  let list = THESAURUS[w];
  if (!list && w.endsWith('s')) list = THESAURUS[w.slice(0, -1)];
  if (!list) return [];
  const cap = word[0] === word[0].toUpperCase();
  return list.map((s) => (cap ? s[0].toUpperCase() + s.slice(1) : s));
}
