// Copies the Latin woff2 subsets of the bundled open-licence fonts into
// src/fonts and writes src/fonts/fonts.css, so the app works fully offline.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'src/fonts');
fs.mkdirSync(out, { recursive: true });

const families = {
  'eb-garamond': 'EB Garamond',
  'crimson-pro': 'Crimson Pro',
  'libre-baskerville': 'Libre Baskerville',
  'lora': 'Lora',
  'merriweather': 'Merriweather',
  'playfair-display': 'Playfair Display',
  'cormorant-garamond': 'Cormorant Garamond',
  'source-serif-4': 'Source Serif 4',
  'alegreya': 'Alegreya',
  'spectral': 'Spectral',
  'inter': 'Inter',
  'montserrat': 'Montserrat',
  'lato': 'Lato',
  'oswald': 'Oswald',
  'cinzel': 'Cinzel',
  'abril-fatface': 'Abril Fatface',
  'great-vibes': 'Great Vibes',
  'courier-prime': 'Courier Prime',
};
const variants = [['400', 'normal'], ['400', 'italic'], ['700', 'normal'], ['700', 'italic']];

let css = '/* Generated by scripts/gen-fonts.mjs — do not edit. */\n';
const list = [];
for (const [slug, name] of Object.entries(families)) {
  const dir = path.join(root, 'node_modules/@fontsource', slug, 'files');
  if (!fs.existsSync(dir)) { console.warn('missing', slug); continue; }
  let any = false;
  for (const [w, s] of variants) {
    const file = `${slug}-latin-${w}-${s}.woff2`;
    const src = path.join(dir, file);
    if (!fs.existsSync(src)) continue;
    fs.copyFileSync(src, path.join(out, file));
    css += `@font-face{font-family:'${name}';font-style:${s};font-weight:${w};font-display:swap;src:url('./${file}') format('woff2');}\n`;
    any = true;
  }
  if (any) list.push(name);
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'families.json'), JSON.stringify(list, null, 2));
console.log('fonts:', list.length);
