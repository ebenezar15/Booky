// Copies the needed woff2 subsets of every bundled font into src/fonts and writes
// src/fonts/fonts.css (with unicode-range per script) plus src/fonts/catalog.json.
import fs from 'node:fs';
import path from 'node:path';
import { FONT_LIST } from './font-list.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'src/fonts');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

let css = '/* Generated by scripts/gen-fonts.mjs — do not edit. */\n';
const catalog = [];
let bytes = 0;
for (const font of FONT_LIST) {
  const dir = path.join(root, 'node_modules/@fontsource', font.slug);
  if (!fs.existsSync(dir)) { console.warn('missing package', font.slug); continue; }
  const got = { weights: new Set(), italic: false };
  const styles = font.italic ? ['normal', 'italic'] : ['normal'];
  for (const w of font.weights) {
    for (const s of styles) {
      const cssFile = path.join(dir, `${w}${s === 'italic' ? '-italic' : ''}.css`);
      if (!fs.existsSync(cssFile)) continue;
      const src = fs.readFileSync(cssFile, 'utf8');
      for (const m of src.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)) {
        const block = m[2];
        const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
        if (!file) continue;
        const subset = font.scripts.find((sc) => file.includes(`-${sc}-${w}-${s}`));
        if (!subset) continue;
        fs.copyFileSync(path.join(dir, 'files', file), path.join(out, file));
        bytes += fs.statSync(path.join(out, file)).size;
        const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
        css += `@font-face{font-family:'${font.name}';font-style:${s};font-weight:${w};font-display:swap;src:url('./${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
        got.weights.add(w);
        if (s === 'italic') got.italic = true;
      }
    }
  }
  if (got.weights.size) {
    catalog.push({ name: font.name, category: font.category, scripts: font.scripts.filter((x) => x !== 'latin-ext'), weights: [...got.weights], italic: got.italic, note: font.note });
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'catalog.json'), JSON.stringify(catalog, null, 1));
console.log(`fonts: ${catalog.length} families, ${(bytes / 1048576).toFixed(1)} MB`);
